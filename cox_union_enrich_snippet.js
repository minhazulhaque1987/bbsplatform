(function enrichCoxFromExcel(){
  if(!Array.isArray(PHC_UPAZILAS_COXSBAZAR) || !PHC_UNIONS_COXSBAZAR) return;
  const norm = (s)=>String(s||'').toLowerCase().replace(/[^a-z0-9]+/g,'');
  for (const upa of PHC_UPAZILAS_COXSBAZAR){
    const enrichSet = PHC_UNION_EXCEL_ENRICH_COXSBAZAR[String(upa.id)] || {};
    const unions = PHC_UNIONS_COXSBAZAR[String(upa.id)] || [];
    let villagesTotal = 0;
    let mouzasTotal = 0;
    for (const u of unions){
      const key = Object.keys(enrichSet).find(k => norm(k) === norm(u.name_en || u.name_bn));
      if(key){
        const e = enrichSet[key];
        u.villages = e.villages ?? u.villages ?? null;
        u.mouzas = e.mouzas ?? u.mouzas ?? null;
        u.pop_total_2022 = e.pop_total_2022 ?? u.pop_total_2022 ?? null;
      }
      villagesTotal += Number(u.villages || 0);
      mouzasTotal += Number(u.mouzas || 0);
    }
    upa.villages = villagesTotal || upa.villages || null;
    upa.mouzas = mouzasTotal || upa.mouzas || null;
  }
})();
